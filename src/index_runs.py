"""Write runs/INDEX.md: one row per run, read from each run's summary.json.

Usage: uv run python src/index_runs.py   (run_queue.sh calls it after every run)
"""
import json

from runs import RUNS, all_runs


def row(rd):
    p = rd / "summary.json"
    rel = rd.relative_to(RUNS).as_posix()
    model, task, name = rel.split("/")
    if not p.exists():
        n = sum(1 for _ in open(rd / "results.jsonl", encoding="utf-8"))
        return f"| {model} | {task} | [{name}]({rel}/) | {n} so far | | | | | | | unfinished or stopped |"
    s = json.loads(p.read_text(encoding="utf-8"))
    if "n" not in s:  # early runs kept only a note
        return f"| {model} | {task} | [{name}]({rel}/) | | | | | | | | {s.get('note', '')} |"
    n = s["n"]
    scope = f"first {s['first']}" if s.get("first") else str(n)
    sampling = s["preset"] + ("" if s.get("think", True) else ", no think")
    return (f"| {model} | {task} | [{name}]({rel}/) | {scope} | {s['max_tokens'] // 1024}k | {sampling} | "
            f"{round(s['acc'] * n)}/{n} | {round(s['truncated'] * n)} | {s['mean_tokens']} | "
            f"{s['mean_waits_per_kchar']} | |")


def main():
    lines = [
        "# Runs",
        "",
        "Generated by `src/index_runs.py`; do not edit by hand. Each run folder holds results.jsonl, summary.json "
        "(exact sampling settings), console.log and transcripts/. What each edit is: `logs/edits.jsonl` and "
        "`docs/STATUS.md`. Stopped or superseded runs are in each task's `_aborted/` folder.",
        "",
        "| model | task | run | problems | cap | sampling | correct | truncated | mean tokens | waits/kchar | note |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(rd) for rd in all_runs()]
    (RUNS / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"runs/INDEX.md: {len(lines) - 6} runs")


if __name__ == "__main__":
    main()
