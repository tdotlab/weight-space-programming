"""Where eval runs live: runs/<model>/<task>/<run>/ holding results.jsonl, summary.json,
console.log, server.log (gitignored) and transcripts/.

<model> is the size from $WSP_MODEL (Qwen3.5-0.8B -> 0.8B). Runs that were stopped or superseded
go in runs/<model>/<task>/_aborted/. runs/INDEX.md is generated by src/index_runs.py.
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"


def model_size(model=None):
    return (model or os.environ.get("WSP_MODEL", "Qwen3.5-0.8B")).split("-")[-1]


def run_dir(name, model=None, task="math500"):
    return RUNS / model_size(model) / task / name


def find(name):
    """Resolve a run by bare name (A64_q8) or by path under runs/ (2B/math500/base_8k_q8)."""
    p = RUNS / name
    if (p / "results.jsonl").exists():
        return p
    hits = [d for d in RUNS.glob(f"*/*/{name}") if (d / "results.jsonl").exists()]
    if len(hits) == 1:
        return hits[0]
    if not hits:
        raise SystemExit(f"no run named {name} under {RUNS}")
    raise SystemExit(f"{name} is ambiguous: " + ", ".join(str(h.relative_to(RUNS)) for h in hits))


def all_runs():
    return sorted(d for d in RUNS.glob("*/*/*") if (d / "results.jsonl").exists())
